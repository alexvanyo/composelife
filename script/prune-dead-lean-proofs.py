"""Finds and removes Lean theorems (and optionally definitions) that no master theorem depends on.

A declaration is live when it is reachable from a master theorem (any theorem declared in a module named
`*Theorems` or `theorems.*`) by following the constants used in declaration types and values. Everything else
in the proof modules (and, with `--defs`, in the specification and model modules) is dead: it proves nothing
about the compiled code.

Usage (from the repository root, after `lake build` of the package):

    script/prune-dead-lean-proofs.py algorithm/lean            # report dead theorems
    script/prune-dead-lean-proofs.py algorithm/lean --apply    # delete them
    script/prune-dead-lean-proofs.py geometry/lean --defs      # also report dead definitions

Deleting a declaration never breaks a live one, but it can leave behind aliases, comments or now-empty modules
that referenced it, so rebuild with `lake build --wfail` after `--apply`.
"""

import argparse
import collections
import os
import re
import subprocess
import sys
import tempfile
import tomllib

LEAN_REPORT = r'''
import Lean
{imports}

open Lean Elab Command

/-- The top-level module name components of this package. -/
def packageModules : List String := [{package_modules}]

/-- Whether `mod` belongs to this package (rather than to a dependency such as Mathlib). -/
def isPackageModule (mod : Name) : Bool :=
  packageModules.contains (mod.getRoot.toString)

/-- Whether `mod` holds master theorems, or mutation proofs (which are kept as evidence the theorems are strong). -/
def isMasterModule (mod : Name) : Bool :=
  isPackageModule mod &&
    ("theorems.".isPrefixOf mod.toString || mod.toString.endsWith "Theorems" || mod.toString.endsWith "Mutations")

/-- Whether dead declarations of `mod` are reported: proof modules, and with `defs` also specs and models. -/
def isPrunableModule (mod : Name) (defs : Bool) : Bool :=
  let s := mod.toString
  isPackageModule mod && ("proofs.".isPrefixOf s || s.endsWith "Proofs" ||
    (defs && ("models.".isPrefixOf s || s.endsWith "Defs")))

elab "#report_dead" defs:ident : command => do
  let defs := defs.getId == `defs
  let env ← getEnv
  let moduleOf (n : Name) : Option Name :=
    (env.getModuleIdxFor? n).map fun i => env.header.moduleNames[i.toNat]!
  let mut stack : List Name := []
  for (n, ci) in env.constants.toList do
    if ci matches .thmInfo _ then
      if let some mod := moduleOf n then
        if isMasterModule mod then stack := n :: stack
  let mut seen : NameSet := {{}}
  while !stack.isEmpty do
    match stack with
    | [] => break
    | n :: rest =>
      stack := rest
      if seen.contains n then continue
      seen := seen.insert n
      if let some ci := env.find? n then
        let used := ci.type.getUsedConstants ++
          ((ci.value? (allowOpaque := true)).map (·.getUsedConstants) |>.getD #[])
        for c in used do
          if !seen.contains c then stack := c :: stack
  for (n, ci) in env.constants.toList do
    if n.isInternal || seen.contains n || env.isProjectionFn n then continue
    -- Tactics, macros and their helpers run at elaboration time, so no proof term mentions them.
    if ci.type.getUsedConstants.any (·.getRoot == `Lean) then continue
    let some mod := moduleOf n | continue
    if !isPrunableModule mod defs then continue
    let kind := match ci with
      | .thmInfo _ => some "theorem"
      | .defnInfo _ => if defs then some "def" else none
      | _ => none
    if let some kind := kind then
      IO.println s!"DEAD {{kind}} {{mod}} {{n}}"

#report_dead {mode}
'''

# Auxiliary declarations generated by the elaborator; they disappear with the declaration they belong to.
AUX = re.compile(r'\.(eq_\d+|eq_def|induct|congr_simp|recOn|casesOn|noConfusion|noConfusionType|ctorIdx|mk|rec|'
                 r'below|brecOn|binductionOn|sizeOf_spec|inj|injEq|ext|ext_iff)$|_unfold$|match_|proof_|_sunfold|'
                 r'\._|\.default$|\.repr$|\.hash$|\.beq$')

# Lines that start a new top-level declaration or command.
TOP = re.compile(r'^(/--|/-!|theorem |lemma |private |protected |def |abbrev |noncomputable |instance |structure |'
                 r'inductive |@\[|set_option |section|end |namespace |open |variable |--|macro |syntax |elab |'
                 r'attribute |example|#)')

DECL = re.compile(r'^(?:private |protected )?(?:noncomputable )?(?:theorem|lemma|def|abbrev) ([^\s(:{\[]+)')

# Commands that open and close scopes; only namespaces add a prefix to the names declared in them.
NAMESPACE = re.compile(r'^namespace (\S+)')
SECTION = re.compile(r'^(?:noncomputable )?section\b')
END = re.compile(r'^end\b')


def lake_roots(package):
    with open(os.path.join(package, 'lakefile.toml'), 'rb') as f:
        config = tomllib.load(f)
    roots = []
    for lib in config.get('lean_lib', []):
        roots.extend(lib.get('roots', [lib['name']]))
    return [r for r in roots if r != 'AxiomAudit']


def report(package, defs):
    imports = '\n'.join(f'import {r}' for r in lake_roots(package))
    package_modules = sorted({r.split('.')[0] for r in lake_roots(package)})
    source = LEAN_REPORT.format(imports=imports, mode='defs' if defs else 'theorems',
                                package_modules=', '.join(f'"{m}"' for m in package_modules))
    with tempfile.NamedTemporaryFile('w', suffix='.lean', delete=False) as f:
        f.write(source)
        path = f.name
    try:
        result = subprocess.run(['lake', 'env', 'lean', path], cwd=package, capture_output=True, text=True)
    finally:
        os.unlink(path)
    if result.returncode != 0:
        sys.exit(f'Lean failed (is the package built?):\n{result.stdout}{result.stderr}')
    dead = collections.defaultdict(list)
    for line in result.stdout.splitlines():
        if not line.startswith('DEAD '):
            continue
        _, kind, mod, name = line.split()
        if AUX.search(name) or any(c.startswith('inst') for c in name.split('.')):
            continue
        dead[mod].append((kind, name))
    return dead


def declaration_names(lines):
    """The fully qualified name of each declaration in `lines`, by line index, following `namespace` and `end`."""
    names = {}
    scopes = []
    depth = 0
    for i, line in enumerate(lines):
        # Skip comment bodies, where a line can start with `end` or `namespace` as prose.
        outside = depth == 0
        depth = max(0, depth + line.count('/-') - line.count('-/'))
        if not outside:
            continue
        if m := NAMESPACE.match(line):
            scopes.append(m.group(1).split('.'))
        elif SECTION.match(line):
            scopes.append([])
        elif END.match(line):
            if scopes:
                scopes.pop()
        elif m := DECL.match(line):
            name = m.group(1)
            if name.startswith('_root_.'):
                names[i] = name.removeprefix('_root_.')
            else:
                names[i] = '.'.join([part for scope in scopes for part in scope] + [name])
    return names


def declaration_spans(lines, wanted):
    """The line ranges of the declarations in `lines` whose fully qualified names are in `wanted`."""
    names = declaration_names(lines)
    spans = []
    i = 0
    while i < len(lines):
        if names.get(i) not in wanted:
            i += 1
            continue
        start = i
        while start > 0:
            prev = lines[start - 1]
            if prev.startswith('@[') or re.match(r'^set_option .* in$', prev):
                start -= 1
            elif prev.rstrip().endswith('-/'):
                # The comment that ends here belongs to the declaration only if it is a docstring, not a `/-! -/`
                # section comment or a plain `/- -/` comment.
                d = start - 1
                while d >= 0 and '/-' not in lines[d]:
                    d -= 1
                if d < 0 or not lines[d].lstrip().startswith('/--'):
                    break
                start = d
            else:
                break
        end = i + 1
        while end < len(lines) and not (lines[end] and not lines[end][0].isspace() and TOP.match(lines[end])):
            end += 1
        spans.append((start, end))
        i = end
    return spans


def referenced_by_name(package, dead):
    """Dead declarations whose name still appears in source text outside every dead declaration.

    A lemma that `simp` or `dsimp` uses by `rfl` leaves no trace in the proof term, and a tactic can mention
    a lemma by name, so such declarations are kept.
    """
    all_names = {name for entries in dead.values() for _, name in entries}
    live_text = []
    for root, _, files in os.walk(package):
        if '.lake' in root:
            continue
        for f in files:
            if not f.endswith('.lean'):
                continue
            lines = open(os.path.join(root, f)).read().split('\n')
            keep = [True] * len(lines)
            for start, end in declaration_spans(lines, all_names):
                for k in range(start, end):
                    keep[k] = False
            live_text.append('\n'.join(l for l, k in zip(lines, keep) if k))
    text = '\n'.join(live_text)
    kept = set()
    for mod, entries in dead.items():
        for _, name in entries:
            short = name.split('.')[-1]
            if re.search(r'(?<![\w.])(?:[\w.]*\.)?' + re.escape(short) + r'(?![\w])', text):
                kept.add(name)
    return kept


def delete(package, mod, names):
    path = os.path.join(package, mod.replace('.', '/') + '.lean')
    lines = open(path).read().split('\n')
    keep = [True] * len(lines)
    spans = declaration_spans(lines, set(names))
    for start, end in spans:
        for k in range(start, end):
            keep[k] = False
    text = '\n'.join(line for line, k in zip(lines, keep) if k)
    open(path, 'w').write(re.sub(r'\n{3,}(?=\S)', '\n\n', text))
    return len(spans)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('package', help='Lean package directory, e.g. algorithm/lean')
    parser.add_argument('--defs', action='store_true', help='also report dead definitions in specs and models')
    parser.add_argument('--apply', action='store_true', help='delete the dead declarations')
    args = parser.parse_args()
    dead = report(args.package, args.defs)
    kept = referenced_by_name(args.package, dead)
    for name in sorted(kept):
        print(f'kept (referenced by name): {name}')
    dead = {mod: [(k, n) for k, n in entries if n not in kept] for mod, entries in dead.items()}
    dead = {mod: entries for mod, entries in dead.items() if entries}
    total = sum(len(v) for v in dead.values())
    for mod in sorted(dead):
        for kind, name in sorted(dead[mod], key=lambda x: x[1]):
            print(f'{mod}: {kind} {name}')
    print(f'{total} dead declarations')
    if args.apply and total:
        for mod in sorted(dead):
            n = delete(args.package, mod, [name for _, name in dead[mod]])
            print(f'{mod}: deleted {n} of {len(dead[mod])}')
        print('Rebuild with `lake build --wfail` and rerun until nothing is left.')


if __name__ == '__main__':
    main()
